/**
 * Shared E2E fixtures: target URLs from the global setup, synthetic accounts and
 * real UI sign-in/sign-out. Accounts are unique per test, so tests stay independent
 * and can run in parallel against the same disposable database.
 */
import { test as base, expect } from '@playwright/test';
import type { APIRequestContext, Page, Request } from '@playwright/test';
import { randomBytes, randomUUID } from 'node:crypto';

export interface Account { email: string; password: string; displayName: string }

export const target = {
    get base() { return process.env.E2E_BASE_URL ?? ''; },
    get api() { return process.env.E2E_API_URL ?? process.env.E2E_BASE_URL ?? ''; },
    /** True only for the disposable stack, whose catalogue fixture is known. */
    get fixture() { return process.env.E2E_STACK === 'disposable'; },
    get instructor(): Account | null {
        // Reserved names from .env.example: an existing Instructor account (generated by the disposable stack).
        const email = process.env.E2E_USERNAME, password = process.env.E2E_PASSWORD;
        // The display name is known only for the generated account; an external one matches any account menu.
        return email && password ? { email, password, displayName: process.env.E2E_STACK === 'disposable' ? 'E2E Course Instructor' : '' } : null;
    },
};

/** Fixture identifiers from fixtures/catalogue-fixture.sql. */
export const fixture = {
    primary: '00000000-0000-4000-8000-000000000002',
    primaryTitle: 'E2E Programming Foundations',
    hidden: '00000000-0000-4000-8000-000000000099',
    longTitle: 'W'.repeat(100),
    longDescription: 'D'.repeat(500),
    publishedCount: 21,
};

export function newAccount(label = 'Learner'): Account {
    return { email: `e2e-${label.toLowerCase()}-${randomUUID()}@example.test`, password: `Learn-${randomBytes(9).toString('hex')}!`, displayName: `E2E ${label} ${randomBytes(2).toString('hex')}` };
}

export async function registerThroughApi(request: APIRequestContext, account: Account) {
    const response = await request.post(new URL('/api/auth/register', target.api).href, { data: account });
    expect(response.status(), 'registration through the API').toBe(201);
}

const escape = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
export const accountMenuName = (account: Account) => new RegExp(`^Account menu, ${account.displayName ? escape(account.displayName) : ''}`);

export async function signIn(page: Page, account: Account) {
    await page.goto('/login');
    await page.locator('#login-email').fill(account.email);
    await page.locator('#login-password').fill(account.password);
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(/\/courses$/);
    await expect(page.getByRole('button', { name: accountMenuName(account) })).toBeVisible();
}

export async function signOut(page: Page, account: Account) {
    await page.getByRole('button', { name: accountMenuName(account) }).click();
    await page.getByRole('menuitem', { name: 'Sign out' }).click();
    await expect(page).toHaveURL(/\/login$/);
}

/** Records whether each API request carried a bearer credential (values are never stored). */
export function watchAuthorization(page: Page) {
    const seen: { method: string; path: string; bearer: boolean }[] = [];
    page.on('request', (request: Request) => {
        const url = new URL(request.url());
        if (!url.pathname.startsWith('/api/')) return;
        seen.push({ method: request.method(), path: url.pathname, bearer: /^Bearer \S+$/.test(request.headers().authorization ?? '') });
    });
    return seen;
}

/** Page-level horizontal overflow (tables may scroll inside their own surface). */
export async function expectNoPageOverflow(page: Page) {
    const size = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }));
    expect(size.scroll, JSON.stringify(size)).toBeLessThanOrEqual(size.client);
}

export const test = base.extend<{ learner: Account }>({
    baseURL: async ({}, use) => { await use(target.base); },
    learner: async ({ request }, use) => {
        const account = newAccount();
        await registerThroughApi(request, account);
        await use(account);
    },
});
